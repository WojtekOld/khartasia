$vid = 'classification_botanique';
$storage = \Drupal::entityTypeManager()->getStorage('taxonomy_term');
$ok = 0; $err = 0;

foreach ($species_to_family as $species_name => $family_name) {
  $species_ids = \Drupal::entityQuery('taxonomy_term')
    ->condition('vid', $vid)->condition('name', $species_name)
    ->accessCheck(FALSE)->execute();
  $family_ids = \Drupal::entityQuery('taxonomy_term')
    ->condition('vid', $vid)->condition('name', $family_name)
    ->accessCheck(FALSE)->execute();

  if (!$species_ids) { echo "ESPECE MANQUANTE: $species_name\n"; $err++; continue; }
  if (!$family_ids)  { echo "FAMILLE MANQUANTE: $family_name\n"; $err++; continue; }

  $term = $storage->load(reset($species_ids));
  $term->set('parent', [reset($family_ids)]);
  $term->save();
  echo "OK: $species_name => $family_name\n";
  $ok++;
}
echo "\n--- $ok liens, $err erreurs ---\n";
